function schema_sql_type(string $type): string {
  switch ($type) {
    case 'uuid': return 'CHAR(36)';
    case 'key': return 'VARCHAR(255)';
    case 'text': return 'TEXT';
    case 'longtext':
    case 'json':
    case 'array': return 'LONGTEXT';
    case 'int': return 'INT';
    case 'bool': return 'TINYINT(1)';
    case 'ts': return 'DATETIME(3)';
    case 'date': return 'DATE';
  }
  throw new RuntimeException("Unknown column type $type");
}
